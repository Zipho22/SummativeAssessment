    private void btnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProcessActionPerformed
        // TODO add your handling code here:
        double price = Double.parseDouble(txtPrice.getText());

ProductCalculations calculations = new ProductCalculations(price);

double vat = calculations.GetVat();
double commission = calculations.GetCommission();
double total = calculations.GetTotal();

javax.swing.JOptionPane.showMessageDialog(this,
    "VAT: R" + vat +
    "\nCommission: R" + commission +
    "\nTotal Sale Amount: R" + total);
try {
    PrintWriter writer = new PrintWriter(
        new FileWriter("data.txt", true));

    writer.println("Customer Name: " + txtCustomerName.getText());
    writer.println("Product: " + cmbProduct.getSelectedItem());
    writer.println("VAT: R" + vat);
    writer.println("Commission: R" + commission);
    writer.println("Total Sale Amount: R" + total);

    writer.println("-------------------------");

    writer.close();

} catch (IOException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
        "Error saving data: " + e.getMessage());
}
    }//GEN-LAST:event_btnProcessActionPerformed

